    print(f"  SKU={sku}: items={items}, realized={realized:.2f}, to_transfer={to_transfer:.2f}, VV={vv:.2f}, delivery={delivery:.2f}, storage={storage:.2f}, acquiring={acquiring:.2f}, fines={fines:.2f}")
